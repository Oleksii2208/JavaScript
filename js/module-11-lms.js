// HTTP ґрунтується на структурі клієнт-сервер і моделі запит-відповідь. Як це працює?

// 1.Клієнтський застосунок ініціює з'єднання, формує запит і відправляє його на сервер.
// 2.Після чого сервер обробляє цей запит, формує відповідь і передає її назад клієнтові.
// 3.Зв'язок між ними здійснюється за допомогою низки перемежованих HTTP-запитів і HTTP-відповідей.
// Запит відбувається в кілька етапів:

// DNS - запит — пошук найближчого DNS - сервера, щоб перетворити адресу(наприклад google.com) в її числове вираження,

// Ця політика безпеки називається CORS(Cross - Origin Resource Sharing), що перекладається як "спільне використання ресурсів
// між різними джерелами".

// Як працює CORS?
// При кожному HTTP - запиті браузер автоматично додає заголовок Origin, де вказує адресу вебсторінки, яка намагається
